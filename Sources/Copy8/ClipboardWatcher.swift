import AppKit

/// Quello che è stato appena copiato, prima di finire in cronologia.
struct Capture {
    var kind: ClipKind
    var text: String
    var rtf: Data?
    var html: Data?
    var imageData: Data?
    var imageIsPNG = false
    var sourceName: String?
    var sourceBundle: String?
}

/// Controlla `changeCount` degli appunti di sistema: un'operazione che non costa quasi nulla.
@MainActor
final class ClipboardWatcher {
    var onCapture: ((Capture) -> Void)?
    var ignoreConfidential: () -> Bool = { true }
    /// Il `changeCount` prodotto da Copy8 stesso quando incolla: non va registrato di nuovo.
    var ignoredChangeCount = -1

    private let pasteboard = NSPasteboard.general
    private var lastChangeCount: Int
    private var timer: Timer?

    private static let maxTextLength = 1_000_000
    private static let maxRichBytes = 4_000_000
    private static let maxImageBytes = 40_000_000

    /// Tipi che chiedono di non essere mai salvati (convenzioni nspasteboard.org).
    private static let transientTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping", "Pasteboard generator type",
    ]
    /// Password e contenuti riservati.
    private static let confidentialTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "com.agilebits.onepassword", "net.antelle.keeweb",
    ]

    init() {
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.4, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.15
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func poll() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard count != ignoredChangeCount, let types = pasteboard.types, !types.isEmpty else { return }

        let names = Set(types.map(\.rawValue))
        if !names.isDisjoint(with: Self.transientTypes) { return }
        if ignoreConfidential(), !names.isDisjoint(with: Self.confidentialTypes) { return }

        let app = NSWorkspace.shared.frontmostApplication
        var capture = Capture(kind: .text, text: "", sourceName: app?.localizedName, sourceBundle: app?.bundleIdentifier)

        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            capture.kind = .file
            capture.text = urls.map(\.path).joined(separator: "\n")
            onCapture?(capture)
            return
        }

        if let string = pasteboard.string(forType: .string),
           !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            guard string.utf16.count <= Self.maxTextLength else { return }
            capture.kind = Detect.kind(for: string, sourceBundle: capture.sourceBundle)
            capture.text = string
            capture.rtf = pasteboard.data(forType: .rtf).flatMap { $0.count <= Self.maxRichBytes ? $0 : nil }
            capture.html = pasteboard.data(forType: .html).flatMap { $0.count <= Self.maxRichBytes ? $0 : nil }
            onCapture?(capture)
            return
        }

        if let png = pasteboard.data(forType: .png) {
            capture.imageData = png
            capture.imageIsPNG = true
        } else if let tiff = pasteboard.data(forType: .tiff) {
            capture.imageData = tiff
        }
        if let data = capture.imageData, data.count <= Self.maxImageBytes {
            capture.kind = .image
            onCapture?(capture)
        }
    }
}
